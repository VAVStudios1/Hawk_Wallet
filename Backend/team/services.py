"""
Team / referral services.

Referral: every user has a unique referral_code (generated by User.save())
and at most one direct referrer, assigned only at registration through
resolve_referrer() and never changed afterwards (User.referrer is an
immutable field). A brand-new user has no descendants, so assignment at
creation can never form a cycle; walks up and down the tree still guard
against one.

Team levels are derived from User.referrer on read - no ancestry table.
Level 1 is the member's direct referrals, level 2 their referrals, and so
on with no depth limit: team views and counts include every level. Only
commission stops at MAX_COMMISSION_LEVEL (21) - a pay-in by a member 22 or
more levels below an ancestor earns that ancestor nothing.

Commission: generate_pay_in_commissions() runs inside the pay-in
confirmation transaction (payins.services._apply_confirmation), so the
confirmation and every commission row and ledger entry commit or roll back
together. See its docstring for the rules.
"""
import itertools
import logging
import re
from decimal import Decimal
from urllib.parse import urlencode

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.paginator import EmptyPage, PageNotAnInteger, Paginator
from django.db import transaction
from django.db.models import Count, Sum

from audit.models import LedgerEntry
from audit.services import record_ledger_entry
from core.models import REFERRAL_CODE_PATTERN
from core.permissions import is_verified_member
from payins.models import PayIn
from team.calculations import MAX_COMMISSION_LEVEL, calculate_commission, commission_rate
from team.exceptions import (
    CommissionError,
    InvalidPage,
    InvalidReferralCode,
    InvalidTeamLevel,
    SelfReferral,
    TeamPermissionDenied,
)
from team.models import Commission

User = get_user_model()

logger = logging.getLogger(__name__)

REFERRAL_CODE_RE = re.compile(REFERRAL_CODE_PATTERN)
ZERO = Decimal('0.00')
PAGE_SIZE = 50
MAX_PAGE_SIZE = 100


# --- referral -----------------------------------------------------------------

def resolve_referrer(referral_code, *, new_user_mobile_number=None):
    """
    Return the active User owning `referral_code`, for assigning as a new
    user's referrer at registration.

    The code is matched case-insensitively after trimming surrounding
    whitespace (codes are uppercase-only). Unknown codes and codes of
    deactivated accounts raise InvalidReferralCode; a code belonging to the
    registering mobile number raises SelfReferral.
    """
    if not isinstance(referral_code, str):
        raise InvalidReferralCode()
    code = referral_code.strip().upper()
    if REFERRAL_CODE_RE.fullmatch(code) is None:
        raise InvalidReferralCode()
    referrer = User.objects.filter(referral_code=code, is_active=True).first()
    if referrer is None:
        raise InvalidReferralCode()
    if new_user_mobile_number is not None and referrer.mobile_number == new_user_mobile_number:
        raise SelfReferral()
    return referrer


def referral_link(referral_code):
    """Invite link, or None until REFERRAL_LINK_BASE_URL is configured."""
    base = settings.REFERRAL_LINK_BASE_URL
    if not base:
        return None
    return f'{base}?{urlencode({"ref": referral_code})}'


def iter_ancestors(user, max_level=MAX_COMMISSION_LEVEL):
    """
    Yield (level, ancestor) walking up from `user`'s direct referrer
    (level 1) to at most `max_level`. Stops early at the root, or - should
    corrupt data ever contain one - at a cycle, which is logged.
    """
    seen = {user.pk}
    referrer_id = User.objects.filter(pk=user.pk).values_list('referrer_id', flat=True).first()
    level = 0
    while referrer_id is not None and level < max_level:
        level += 1
        if referrer_id in seen:
            logger.error('Referral cycle detected above user %s at level %s', user.pk, level)
            return
        seen.add(referrer_id)
        ancestor = User.objects.only(
            'id', 'referrer_id', 'is_active', 'is_verified', 'role'
        ).get(pk=referrer_id)
        yield level, ancestor
        referrer_id = ancestor.referrer_id


def iter_team_levels(user, max_level=None):
    """
    Yield (level, [user ids]) for each non-empty level of `user`'s team,
    level 1 = direct referrals, down to `max_level` (default: the whole
    tree, however deep). One query per level; ends at the first empty level.
    """
    seen = {user.pk}
    frontier = [user.pk]
    levels = itertools.count(1) if max_level is None else range(1, max_level + 1)
    for level in levels:
        ids = [
            pk for pk in User.objects.filter(referrer_id__in=frontier).values_list('id', flat=True)
            if pk not in seen
        ]
        if not ids:
            return
        seen.update(ids)
        yield level, ids
        frontier = ids


# --- commission ---------------------------------------------------------------

def generate_pay_in_commissions(*, payin, order, actor):
    """
    Create the team commissions for the just-confirmed `payin` and return
    them. Must run inside the confirmation transaction, after the PayIn is
    saved as CONFIRMED.

    Walks up from the payer: level 1 earns 0.3% of the confirmed pay-in
    amount, levels 2-21 earn 0.1%; nothing above level 21. Only active,
    verified MEMBER ancestors are paid; an ineligible ancestor is skipped
    but still occupies its level, so everyone above keeps their true level.
    Amounts are rounded half-up to paise; a level whose amount rounds to 0
    gets no record. Each commission is written with a COMMISSION_EARNED
    ledger entry (actor = confirming admin, no balances).

    Idempotent: if the pay-in already has commissions they are returned and
    nothing is written. The unique constraints (payin, level) and
    (payin, beneficiary) are the database-level guard; a violation raises
    IntegrityError and rolls back the whole confirmation.
    """
    if not transaction.get_connection().in_atomic_block:
        raise CommissionError('Commissions must be generated inside the confirmation transaction.')
    if payin.status != PayIn.Status.CONFIRMED or payin.order_id != order.pk:
        raise CommissionError('Commissions are only generated for a confirmed pay-in.')

    existing = list(Commission.objects.filter(payin=payin).order_by('level'))
    if existing:
        return existing

    base_amount = payin.amount
    created = []
    for level, ancestor in iter_ancestors(payin.user):
        if not is_verified_member(ancestor):
            continue
        rate = commission_rate(level)
        amount = calculate_commission(base_amount, rate)
        if amount <= 0:
            continue
        commission = Commission.objects.create(
            beneficiary=ancestor,
            source_user_id=payin.user_id,
            payin=payin,
            level=level,
            rate=rate,
            base_amount=base_amount,
            amount=amount,
        )
        record_ledger_entry(
            actor=actor,
            action=LedgerEntry.Action.COMMISSION_EARNED,
            order=order,
            payin=payin,
            commission=commission,
            amount=amount,
            reference_id=order.reference,
        )
        created.append(commission)
    return created


# --- member reads -------------------------------------------------------------

def _require_member(user):
    if not is_verified_member(user):
        raise TeamPermissionDenied()


def total_commission(user):
    total = Commission.objects.filter(beneficiary=user).aggregate(total=Sum('amount'))['total']
    return total if total is not None else ZERO


def get_referral_info(*, user):
    _require_member(user)
    levels = list(iter_team_levels(user))
    return {
        'referral_code': user.referral_code,
        'referral_link': referral_link(user.referral_code),
        'direct_team_count': len(levels[0][1]) if levels else 0,
        'total_team_count': sum(len(ids) for _, ids in levels),
        'total_commission': total_commission(user),
    }


def get_team_summary(*, user):
    """
    Per-level member counts and commission earned. Always lists levels
    1-21, plus any deeper level that has members; deeper levels have no
    rate and never any commission.
    """
    _require_member(user)
    counts = {level: len(ids) for level, ids in iter_team_levels(user)}
    deepest = max(counts, default=0)
    earned = {
        row['level']: row
        for row in Commission.objects.filter(beneficiary=user)
        .order_by()
        .values('level')
        .annotate(total=Sum('amount'), count=Count('id'))
    }
    levels = [
        {
            'level': level,
            'commission_eligible': level <= MAX_COMMISSION_LEVEL,
            'rate': commission_rate(level),
            'member_count': counts.get(level, 0),
            'commission_count': earned.get(level, {}).get('count', 0),
            'commission_total': earned.get(level, {}).get('total', ZERO),
        }
        for level in range(1, max(MAX_COMMISSION_LEVEL, deepest) + 1)
    ]
    return {
        'direct_team_count': counts.get(1, 0),
        'total_team_count': sum(counts.values()),
        'commission_level_team_count': sum(
            n for level, n in counts.items() if level <= MAX_COMMISSION_LEVEL
        ),
        'total_commission': total_commission(user),
        'commission_count': sum(level['commission_count'] for level in levels),
        'levels': levels,
    }


def list_team_members(*, user, level=None):
    """
    Return [(level, member)] for `user`'s whole team, every level (or only
    `level`), ordered by level then join date.
    """
    _require_member(user)
    wanted = _parse_level(level)
    level_of = {}
    for current, ids in iter_team_levels(user, max_level=wanted):
        if wanted is None or current == wanted:
            level_of.update(dict.fromkeys(ids, current))
    members = User.objects.filter(pk__in=level_of).only('id', 'name', 'mobile_number', 'date_joined')
    return sorted(
        ((level_of[m.pk], m) for m in members),
        key=lambda item: (item[0], item[1].date_joined, item[1].pk),
    )


def list_commissions(*, user):
    _require_member(user)
    return (
        Commission.objects.filter(beneficiary=user)
        .select_related('source_user', 'payin__order')
        .order_by('-created_at', '-id')
    )


def _parse_level(level):
    if level is None or level == '':
        return None
    try:
        value = int(level)
    except (TypeError, ValueError):
        raise InvalidTeamLevel()
    if str(value) != str(level).strip() or value < 1:
        raise InvalidTeamLevel()
    return value


def paginate(items, page, page_size=None):
    """Return (page_items, meta) for a list or queryset."""
    try:
        size = int(page_size) if page_size not in (None, '') else PAGE_SIZE
    except (TypeError, ValueError):
        raise InvalidPage('page_size must be a whole number from 1 to 100.')
    if not 1 <= size <= MAX_PAGE_SIZE:
        raise InvalidPage('page_size must be a whole number from 1 to 100.')
    paginator = Paginator(items, size)
    try:
        current = paginator.page(page or 1)
    except (EmptyPage, PageNotAnInteger):
        raise InvalidPage()
    return list(current.object_list), {
        'page': current.number,
        'page_size': size,
        'total': paginator.count,
        'has_next': current.has_next(),
    }
